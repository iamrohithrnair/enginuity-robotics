def product(text):
    pass
    return normalise_product(text.encode("utf-8")).decode("utf-8")

EVIDENCE = os.path.join(ROOT, "research", "evidence", "postgen")
CLI = os.path.join(ROOT, "python", "robocraft_post", "cli.py")




KNOWN_DIVERGENCES = {
    ("errors/unreachable", "UnreachProg.mod"): (
        "[0.00000000,1.00000000,0.00000000,0.00000000]",
        "[0.00000000,1.00000000,0.00000000,-0.00000000]",
    ),
}


def captured_cases():
    pass
    files = glob.glob(os.path.join(EVIDENCE, "**", "intermediate_*.py"), recursive=True)
    return sorted((f, os.path.dirname(f)) for f in files)


def reference_for(folder, name):
    path = os.path.join(folder, name)
    if os.path.exists(path):
        return path
    stem, ext = os.path.splitext(name)
    
    for f in sorted(os.listdir(folder)):
        if f.startswith(stem + "_") and f.endswith(ext) and not f.startswith("intermediate"):
            return os.path.join(folder, f)
    return None


def gzip_name(data):
    return data[10 : data.index(b"\0", 10)]


class CapturedParityTest(unittest.TestCase):
    pass

    def test_every_captured_generation(self):
        compared = 0
        for intermediate, folder in captured_cases():
            rel = os.path.relpath(folder, EVIDENCE)
            with open(intermediate, encoding="utf-8") as fh:
                source = fh.read()
            res = run(source)
            if parse(source).raised is not None:
                continue  
            with self.subTest(case=rel):
                self.assertTrue(res.ok, res.error)
                for name, content in res.files:
                    ref = reference_for(folder, name)
                    self.assertIsNotNone(ref, "the reference application produced no %s in %s" % (name, rel))
                    with open(ref, "rb") as fh:
                        expected = fh.read()
                    compared += 1
                    if isinstance(content, bytes):
                        
                        self.assertEqual(normalise_product(gzip.decompress(content)), normalise_product(gzip.decompress(expected)), name)
                        self.assertEqual(content[:4], expected[:4])
                        self.assertEqual(content[8:10], expected[8:10], "XFL/OS bytes")
                        self.assertEqual(gzip_name(content), gzip_name(expected))
                        continue
                    text = content
                    if (rel, name) in KNOWN_DIVERGENCES:
                        ours, theirs = KNOWN_DIVERGENCES[(rel, name)]
                        self.assertIn(ours, text)
                        text = text.replace(ours, theirs)
                    self.assertEqual(product(text), product(expected.decode("utf-8")), "%s/%s" % (rel, name))
        self.assertGreaterEqual(compared, 36)

