class ErrorPathTest(unittest.TestCase):
    def _stream(self, post, extra="", body=""):
        return "\n".join(
            [
                'r = RobotPost(r"""%s""",r"""Robot X""",6%s)' % (post, extra),
                'r.ProgStart(r"""LongProg""")',
                body,
                'r.ProgFinish(r"""LongProg""")',
                'r.ProgSave(r"""""",r"""LongProg""",False,False)',
            ]
        )

    def test_missing_post(self):
        pass
        res = run(self._stream("Fanuc_R30iA"))
        self.assertFalse(res.ok)
        self.assertIn("Select a Post Processor for the robot Robot X", res.error)

    def test_post_name_with_py_extension(self):
        pass
        self.assertIs(get_post("ABB_RAPID_IRC5.py"), get_post("ABB_RAPID_IRC5"))

    def test_fanuc_cannot_split(self):
        pass
        body = "\n".join(["r.MoveJ(None,[%i,0,0,0,0,0],None)" % i for i in range(12)])
        res = run(self._stream("Fanuc_R30i", ", lines_x_prog=5", body))
        self.assertFalse(res.ok)
        self.assertIn("Only one program at a time can be split into smaller programs", res.error)
        self.assertIn("Can't split M_LongProg: Two or more programs are split into smaller programs", res.stdout)

    def test_licence_gate_file(self):
        pass
        with open(os.path.join(EVIDENCE, "errors", "license_gate", "intermediate_PostErrProg_license_gated.py"), encoding="utf-8") as fh:
            res = run(fh.read())
        self.assertFalse(res.ok)
        self.assertTrue(res.error.startswith("Exception: Your license does not allow generating programs for ABB IRB 120-3/0.6."))


class IntermediateSafetyTest(unittest.TestCase):
    pass

    def test_code_is_rejected(self):
        for bad in (
            "__import__('os').system('echo hacked')",
            "r = RobotPost(__import__('os').getcwd())",
            "r.ProgStart(open('/etc/passwd').read())",
            "r.__class__ = None",
            "exec('1')",
        ):
            with self.subTest(source=bad):
                with self.assertRaises(IntermediateError):
                    parse(bad)

    def test_unknown_instruction_is_rejected(self):
        with self.assertRaises(IntermediateError):
            parse("r.save_file('x', 'y')")

    def test_escaped_strings_and_multiline_messages(self):
        stream = parse('r = RobotPost("ABB_RAPID_IRC5","R",6)\nr.RunMessage("say \\"\\"\\"hi\\"\\"\\"")\nr.RunMessage(r"""two\nlines""",True)')
        self.assertEqual(stream.steps[0][2], ['say """hi"""'])
        self.assertEqual(stream.steps[1][2], ["two\nlines", True])


class CliTest(unittest.TestCase):
    def test_cli_round_trip_with_binary_urp(self):
        with open(os.path.join(EVIDENCE, "Universal_Robots", "intermediate_PostPgProg.py"), encoding="utf-8") as fh:
            source = fh.read()
        out = subprocess.run([sys.executable, "-I", CLI], input=json.dumps({"intermediate": source}), capture_output=True, text=True, check=False)
        reply = json.loads(out.stdout)
        self.assertTrue(reply["ok"], reply.get("error"))
        self.assertEqual(reply["total"], 12)
        names = [f["name"] for f in reply["files"]]
        self.assertEqual(names, ["PgProg.script", "PgProg.urp"])
        urp = base64.b64decode(reply["files"][1]["content"])
        self.assertIn(b"<cachedContents>def PgProg():", gzip.decompress(urp))
        self.assertIn("SAVED: ", reply["log"])

    def test_cli_lists_posts(self):
        out = subprocess.run([sys.executable, "-I", CLI, "--list"], capture_output=True, text=True, check=True)
        names = {p["name"]: p["assumed"] for p in json.loads(out.stdout)}
        
        for name in ("ABB_RAPID_IRC5", "KUKA_KRC4", "Universal_Robots", "Fanuc_R30i", "KUKA_KRC2", "Fanuc_RJ3", "Post_Generic", "Comau_C5G"):
            self.assertFalse(names[name], name)


