
























import re

from ..base import RobotPost, register
from .turin import euler_xyz






HEADER = '''# Program generated by Enginuity for Automata EVA robots.
# Run this file with Python on a computer that reaches the robot; it needs the evasdk package
# (python3 -m pip install evasdk).
import sys
import time
from math import pi

try:
    from evasdk import Eva
except ImportError:
    sys.exit("This program needs the evasdk package: python3 -m pip install evasdk")

ROBOT_IP = "<IP>"
API_TOKEN = ""  # the robot's API token (EVA settings)


class ComRobot:
    """Runs the program's instructions on an EVA robot through evasdk."""

    def __init__(self):
        self.eva = None
        self.speed = 100.0  # mm/s, also used as the joint speed limit in m/s / 1000
        self.tool = [0, 0, 0, 0, 0, 0]

    def connect(self, ip, token):
        print("Connecting to robot %s" % ip)
        try:
            self.eva = Eva(ip, token)
            with self.eva.lock():
                self.eva.control_wait_for_ready()
            print("Robot name: %s" % self.eva.name())
            return True
        except Exception as e:
            print(e)
            self.eva = None
            return False

    def MoveJ(self, values):
        joints = [v * pi / 180.0 for v in values[:6]]
        with self.eva.lock():
            self.eva.control_go_to(joints, max_speed=self.speed / 1000.0, mode="automatic")
        return True

    def MoveL(self, values):
        print("Linear moves are not available with this driver: instruction skipped")
        return False

    def MoveC(self, values):
        print("Circular moves are not available with this driver: instruction skipped")
        return False

    def setTool(self, pose):
        self.tool = list(pose)
        return True

    def setSpeed(self, values):
        if values[0] != -1:
            self.speed = values[0]
        return True

    def setDO(self, values):
        with self.eva.lock():
            self.eva.gpio_set(values[0], values[1])
        return True

    def WaitDI(self, values):
        number, state = values[0], values[1]
        timeout = values[2] if len(values) > 2 else -1
        start = time.time()
        while True:
            with self.eva.lock():
                if self.eva.gpio_get(number, "input") == state:
                    return True
            if 0 <= timeout < time.time() - start:
                return False
            time.sleep(0.1)


def ConnectRobot():
    global robot
    robot = ComRobot()
    while not robot.connect(ROBOT_IP, API_TOKEN):
        print("Retrying connection...")
        time.sleep(0.5)
    print("Connected to robot: " + ROBOT_IP)


'''

JOINT_TARGET = "#%s movement using joint targets is not supported. Change the target type to cartesian or use a joint movement."


def _pose(pose) -> str:
    v = [pose[0][3], pose[1][3], pose[2][3]] + euler_xyz(pose)
    return "%.3f, %.3f, %.3f,  %.3f, %.3f, %.3f" % tuple(v)


def _joints(joints) -> str:
    return ",".join("%.6f" % v for v in joints)


@register
class Automata(RobotPost):
    name = "Automata"

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.TEXT = ""
        self.MAIN = None

    def addline(self, line):
        self.TEXT += "    " + line + "\n"

    def ProgStart(self, progname):
        if self.MAIN is None:
            self.MAIN = progname
        self.TEXT += "# Program Start,%s\ndef %s():\n    global robot\n    # Generating program: %s\n\n" % (progname, progname, progname)

    def ProgFinish(self, progname):
        self.TEXT += "    return\n\n"

    def ProgSave(self, folder, progname, ask_user=False, show_result=False):
        text = HEADER.replace("<IP>", self.IP_COM) + self.TEXT
        text += 'if __name__ == "__main__":\n    # Connect to the robot and run the program\n    ConnectRobot()\n    %s()\n' % (self.MAIN or progname)
        self.save_file(folder, "%s.py" % progname, text)

    def ProgSendRobot(self, robot_ip, remote_path, ftp_user, ftp_pass):
        self.popup("Sending programs to the robot is not available in Enginuity")

    def MoveJ(self, pose, joints, conf_RLF=None):
        self.addline("robot.MoveJ([%s])" % _joints(joints))

    def MoveL(self, pose, joints, conf_RLF=None):
        if pose is None:
            self.addline(JOINT_TARGET % "Linear")
            return
        self.addline("robot.MoveL([%s,%s])" % (_joints(joints), _pose(pose)))

    def MoveC(self, pose1, joints1, pose2, joints2, conf_RLF_1=None, conf_RLF_2=None):
        if pose1 is None or pose2 is None:
            self.addline(JOINT_TARGET % "Circular")
            return
        self.addline("robot.MoveC([%s,%s,%s,%s])" % (_joints(joints1), _pose(pose1), _joints(joints2), _pose(pose2)))

    def setFrame(self, pose, frame_id=None, frame_name=None):
        self.addline("#robot ref frame set to " + _pose(pose))

    def setTool(self, pose, tool_id=None, tool_name=None):
        self.addline("robot.setTool([%s])" % _pose(pose))
        self.TEXT += "\n"

    def Pause(self, time_ms):
        if time_ms < 0:
            self.addline("print('STOP')")
        else:
            self.addline("import time")
            self.addline("time.sleep(%.3f)" % (time_ms * 1000.0))

    def setSpeed(self, speed_mms):
        self.addline("robot.setSpeed([%r,-1,-1,-1])" % speed_mms)

    def setAcceleration(self, accel_mmss):
        pass

    def setSpeedJoints(self, speed_degs):
        pass

    def setAccelerationJoints(self, accel_degss):
        pass

    def setZoneData(self, zone_mm):
        pass

    def setDO(self, io_var, io_value):
        self.addline("robot.setDO([%s,%s])" % (io_var, io_value))

    def setAO(self, io_var, io_value):
        self.setDO(io_var, io_value)

    def waitDI(self, io_var, io_value, timeout_ms=-1):
        timeout = timeout_ms if timeout_ms is None or timeout_ms < 0 else timeout_ms / 1000.0
        self.addline("robot.WaitDI([%s,%s,%s])" % (io_var, io_value, timeout))

    def RunCode(self, code, is_function_call=False):
        if is_function_call:
            self.addline(re.sub(r"[^A-Za-z0-9_()]", "", code) + "()")
        else:
            self.TEXT += code + "\n"

    def RunMessage(self, message, iscomment=False):
        self.addline("#%s" % message if iscomment else "print('%s')" % message)
