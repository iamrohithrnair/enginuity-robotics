 
 
 
 
 
 
import { writeFileSync } from "node:fs";
import path from "node:path";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";
import { Icon, InstructionIcon, ItemIcon, type IconName } from "@/components/icons";
import { ANIMATED_ICONS, type AnimatedIconId } from "@/components/icons/animated-icons";
import { ICON_MARKUP } from "@/components/icons/markup.generated";

const GENERATED = path.resolve(import.meta.dirname, "../../src/components/icons/markup.generated.ts");
const ids = Object.keys(ANIMATED_ICONS).sort() as AnimatedIconId[];
const names = Object.keys(Icon) as IconName[];

 
const SVG_ATTRS = {
  xmlns: "http://www.w3.org/2000/svg",
  viewBox: "0 0 24 24",
  fill: "none",
  stroke: "currentColor",
  "stroke-width": "2",
  "stroke-linecap": "round",
  "stroke-linejoin": "round",
};

 
function resting(id: AnimatedIconId) {
  const C = ANIMATED_ICONS[id];
  const html = renderToStaticMarkup(createElement(C, { size: 24 }));
  const open = html.indexOf("<svg");
  const body = html.indexOf(">", open) + 1;
  const attrs = Object.fromEntries([...html.slice(open, body).matchAll(/([\w:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
  return { attrs, inner: html.slice(body, html.lastIndexOf("</svg>")) };
}

 
function withoutIdentityStyles(markup: string) {
  return markup.replace(/ style="([^"]*)"/g, (_m, css: string) => {
    const decls = css.split(";").filter(Boolean);
    const moved = decls.some((d) => d.startsWith("transform:") && d !== "transform:none");
    const kept = decls.filter((d) => d !== "transform:none" && d !== "opacity:1" && (moved || !/^transform-(origin|box):/.test(d)));
    return kept.length ? ` style="${kept.join(";")}"` : "";
  });
}

const render = (name: IconName, props: Record<string, unknown> = {}) => renderToStaticMarkup(createElement(Icon[name], props));
const isAnimated = (html: string) => ids.some((id) => html.includes(`>${ICON_MARKUP[id]}</svg>`));

describe("animated icons", () => {
  it("draw their resting markup until animated", () => {
    const markup: Record<string, string> = {};
    for (const id of ids) {
      const { attrs, inner } = resting(id);
      const { style, width, height, class: cls, ...rest } = attrs;
      expect(rest, id).toEqual(SVG_ATTRS);
      expect([width, height], id).toEqual(["24", "24"]);
       
      if (cls !== undefined) expect(cls, id).toMatch(/^lucide( lucide-[a-z0-9-]+)+$/);
       
      if (style !== undefined) expect(style, id).toMatch(/^(transform(-origin|-box)?:[^;]+;?)+$/);
      if (style !== undefined) expect(style, id).toContain("transform:none");
      expect(inner, id).toMatch(/^<(path|circle|rect|line|polyline|polygon|ellipse|g)\b/);
      markup[id] = withoutIdentityStyles(inner);
    }
    if (process.env.UPDATE_ICON_MARKUP) {
      const lines = ids.map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(markup[id])},`);
      writeFileSync(
        GENERATED,
        [
          "// Generated by tests/ui/icons.test.ts (UPDATE_ICON_MARKUP=1): the resting SVG children of every animated",
          "// icon in src/components/icons.tsx, rendered from its animated component. Lucide artwork, ISC License,",
          "// Copyright (c) 2026 Lucide Icons and Contributors (see THIRD_PARTY_NOTICES.md).",
          "export const ICON_MARKUP: Record<string, string> = {",
          ...lines,
          "};",
          "",
        ].join("\n"),
      );
      return;
    }
    expect(ICON_MARKUP).toEqual(markup);
  });

  it("keep the styles that change the drawing", () => {
    expect(withoutIdentityStyles('<path style="transform-box:view-box;transform:none;transform-origin:12px 12px 0"></path>')).toBe("<path></path>");
    expect(withoutIdentityStyles('<g style="transform:scale(0);transform-origin:50% 50%;opacity:1"></g>')).toBe('<g style="transform:scale(0);transform-origin:50% 50%"></g>');
    expect(withoutIdentityStyles('<path style="opacity:0"></path>')).toBe('<path style="opacity:0"></path>');
  });

  it("are each used by an Icon key", () => {
    const html = names.map((n) => render(n)).join("\n");
    for (const id of ids) expect(html.includes(ICON_MARKUP[id]), id).toBe(true);
  });
});

describe("Icon API", () => {
  it("renders every key as a 16 px SVG by default and honours size", () => {
    expect(names.length).toBe(83);
    for (const name of names) {
      expect(render(name), name).toMatch(/^<svg[^>]* width="16" height="16"/);
      expect(render(name, { size: 22 }), name).toMatch(/^<svg[^>]* width="22" height="22"/);
    }
  });

  it("draws animated icons with the library's stroke until hovered", () => {
    expect(render("Settings")).toBe(
      '<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
        ICON_MARKUP["lucide/settings"] +
        "</svg>",
    );
  });

  it("applies color to animated and own glyphs alike", () => {
    expect(render("Sparkle", { color: "#fff" })).toMatch(/^<svg[^>]* color="#fff"/);
    expect(render("Robot", { color: "var(--ink-3)" })).toMatch(/^<svg[^>]* color="var\(--ink-3\)"/);
  });

  it("keeps the robot-specific glyphs and uses the libraries elsewhere", () => {
    const own: IconName[] = ["Station", "Robot", "Frame", "Tool", "JointTarget", "MoveJ", "MoveL", "MoveC", "Rounding", "Grid", "CloseUp", "NoCursor", "Perspective"];
    for (const name of names) expect(isAnimated(render(name)), name).toBe(!own.includes(name));
  });

  it("maps tree items and program instructions to their icons", () => {
    const item = (type: string, isJoint?: boolean) => renderToStaticMarkup(createElement(ItemIcon, { type, isJoint }));
    expect(item("camera")).toContain(ICON_MARKUP["lucide-animated/cctv"]);
    expect(item("program")).toContain(ICON_MARKUP["lucide/file-code"]);
    expect(item("machining")).toContain(ICON_MARKUP["lucide/route"]);
    expect(item("target")).toContain(ICON_MARKUP["lucide/target"]);
    expect(item("target", true)).toBe(renderToStaticMarkup(createElement(Icon.JointTarget, { size: 15 })));
    expect(item("unknown-type")).toContain(ICON_MARKUP["lucide/box"]);
    expect(item("robot")).toMatch(/width="15"/);

    const ins = (kind?: string, moveType?: string) => renderToStaticMarkup(createElement(InstructionIcon, { kind, moveType }));
    expect(ins("move", "linear")).toBe(renderToStaticMarkup(createElement(Icon.MoveL, { size: 14 })));
    expect(ins("move", "joint")).toBe(renderToStaticMarkup(createElement(Icon.MoveJ, { size: 14 })));
    expect(ins("pause")).toContain(ICON_MARKUP["lucide/pause"]);
    expect(ins("print")).toContain(ICON_MARKUP["lucide/message-square"]);
    expect(ins("io")).toContain(ICON_MARKUP["lucide/toggle-right"]);
    expect(ins(undefined)).toContain(ICON_MARKUP["lucide/code-xml"]);
  });
});
