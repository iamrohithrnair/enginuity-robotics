// Verifies post-processor intermediate formatting, call streams, and end-to-end code generation.
 
 
 
import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { buildIntermediate, fmtG, fmtJoints, fmtPose, fmtValue, generationSettings, poseFromP, pyStr, sanitizeProgramName } from "@/engine/commands/generate";
import { mul } from "@/engine/math";
import { absPose } from "@/engine/workspace";
import { engine, ROOT } from "../helpers";

const EVIDENCE = path.join(ROOT, "research/evidence/postgen");

 
function calls(text: string): string[] {
  const lines = text.split(/\r?\n/);
  const start = lines.findIndex((l) => l.startsWith("r.ProgStart("));
  const save = lines.findIndex((l) => l.startsWith("r.ProgSave("));
  return lines.slice(start, save).map((l) => (l.startsWith('r.RunMessage(r"""Program generated by ') ? "<header message>" : l));
}

type E = Awaited<ReturnType<typeof engine>>;
const id = (r: unknown) => (r as { id: string }).id;

async function abbStation() {
  const e = await engine();
  await e.run("library.load", { file: "ABB-IRB-120-3-0-6.robot" });
  const robot = Object.values(e.ws.items).find((i) => i.type === "robot")!;
  return { e, robot };
}

async function frameAt(e: E, robotId: string, name: string, p: [number, number, number, number, number, number]) {
   
  return id(await e.run("item.addFrame", { name, parent: e.ws.activeStation!, pose: mul(absPose(e.ws, robotId), poseFromP(...p)) }));
}

async function target(e: E, robot: string, parent: string, name: string, p: number[] | null, joints: number[]) {
  if (!p) return id(await e.run("target.add", { name, parent, robot, joints, isJoint: true }));
  return id(await e.run("target.add", { name, parent, robot, pose: poseFromP(...(p as [number, number, number, number, number, number])), joints, isJoint: false }));
}

describe("POST-FORMAT: numbers in the intermediate file", () => {
  it("R-POSTGEN-24: %g with MAX_DECIMALS_POST significant digits", () => {
    expect(fmtG(1234.56789)).toBe("1234.57");
    expect(fmtG(-98.7654321)).toBe("-98.7654");
    expect(fmtG(3.13389e-14)).toBe("3.13389e-14");
    expect(fmtG(1e-5)).toBe("1e-05");
    expect(fmtG(123456789)).toBe("1.23457e+08");
    expect(fmtG(100000)).toBe("100000");
    expect(fmtG(1e6)).toBe("1e+06");
    expect(fmtG(0.0001)).toBe("0.0001");
    expect(fmtG(50.5)).toBe("50.5");
    expect(fmtG(1234.56789, 10)).toBe("1234.56789");
    expect(fmtG(-98.7654321, 10)).toBe("-98.7654321");
  });

  it("R-POSTGEN-24: |v| < 5e-7 is written as 0 except the last joint", () => {
    expect(fmtValue(2e-14, 6)).toBe("0");
    expect(fmtJoints([1e-9, -10, 20, 0, 30, 3.13389e-14], 6)).toBe("[0,-10,20,0,30,3.13389e-14]");
  });

  it("R-POSTGEN-25: p(x,y,z,a,b,c) = transl·rotz(a)·roty(b)·rotx(c)", () => {
    expect(fmtPose(poseFromP(1234.57, -98.7654, 50.5, 30, 0, 0), 6)).toBe("p(1234.57,-98.7654,50.5,30,0,0)");
    expect(fmtPose(poseFromP(10, 20, 150, 0, 0, 15), 6)).toBe("p(10,20,150,0,0,15)");
    expect(fmtPose(poseFromP(-353.026, -90.1345, 331.702, 178.023, 40.6496, -169.444), 6)).toBe("p(-353.026,-90.1345,331.702,178.023,40.6496,-169.444)");
  });

  it("R-POSTGEN-20: program names drop characters outside [a-zA-Z0-9_]", () => {
    expect(sanitizeProgramName("Bare Prog-1 (x)")).toBe("BareProg1x");
  });

  it("strings that cannot be raw triple-quoted are escaped instead of breaking the file", () => {
    expect(pyStr("Frame Pg")).toBe('r"""Frame Pg"""');
    expect(pyStr('say """hi"""')).toBe('"say \\"\\"\\"hi\\"\\"\\""');
    expect(pyStr("ends with \\")).toBe('"ends with \\\\"');
  });
});

describe("POST-CALLS: call stream equals RoboDK's intermediate file", () => {
  it("R-POSTGEN-23: the 28-instruction probe program (PgProg)", async () => {
    const { e, robot } = await abbStation();
    const r = robot.id;
    const frame = await frameAt(e, r, "Frame Pg", [1234.57, -98.7654, 50.5, 30, 0, 0]);
    const tool = id(await e.run("robot.addTool", { name: "Tool Pg", pose: poseFromP(10, 20, 150, 0, 0, 15) }));
    const tool2 = id(await e.run("robot.addTool", { name: "Tool2", pose: poseFromP(0, 0, 200, 0, 0, 0) }));
    const q0 = [0, -10, 20, 0, 30, 3.13389e-14];
    const T1 = await target(e, r, frame, "T1", [-640.584, 506.98, 371.534, 150, 50, -165], q0);
    const T2 = await target(e, r, frame, "T2", [-607.85, 543.849, 363.215, 150, 50, -165], q0);
    const T3 = await target(e, r, frame, "T3", [-602.951, 596.788, 316.595, 150, 50, -165], q0);
    const T4 = await target(e, r, frame, "T4", [-663.517, 575.988, 286.611, 150, 50, -165], q0);
    const T5 = await target(e, r, frame, "T5", null, [20, -10, 20, 0, 30, 0]);
    const T6 = await target(e, r, frame, "T6", [-650.861, 503.437, 361.399, 150, 50, -165], q0);
    const T8 = await target(e, r, frame, "T8", null, [10, -15, 25, 5, 35, 5]);
    const T7 = await target(e, r, frame, "T7", [-353.026, -90.1345, 331.702, 178.023, 40.6496, -169.444], [-5, -5, 15, 10, 40, -10]);
    const prog = id(await e.run("program.add", { name: "PgProg", robot: r }));
    const ins = (kind: string, extra: Record<string, unknown> = {}) => e.run("program.addInstruction", { program: prog, kind, ...extra });
    await ins("frame", { frame });
    await ins("tool", { tool });
    await ins("speed", { linear: 250 });
    await ins("rounding", { rounding: 5 });
    await e.run("program.addMoveJ", { program: prog, target: T1 });
    await e.run("program.addMoveL", { program: prog, target: T2 });
    await e.run("program.addMoveC", { program: prog, via: T3, target: T4 });
    await e.run("program.addMoveJ", { program: prog, target: T5 });
    await ins("speed", { linear: 100, joint: 60, linearAccel: 800, jointAccel: 120 });
    await e.run("program.addMoveL", { program: prog, target: T6 });
    await ins("rounding", { rounding: 0 });
    await e.run("program.addMoveL", { program: prog, target: T1 });
    await ins("pause", { pauseMs: 500 });
    await ins("pause", { pauseMs: -1 });
    await ins("print", { text: "Hello from postgen" });
    await ins("comment", { text: "a comment" });
    await ins("call", { text: "SubProgram" });
    await ins("code", { text: "CustomCode(42)" });
    await ins("thread", { text: "ThreadProg" });
    await ins("io", { ioMode: "set", ioName: "1", ioValue: "1" });
    await ins("io", { ioMode: "set", ioName: "Valve", ioValue: "0" });
    await ins("io", { ioMode: "set", ioName: "3", ioValue: "2.5", analog: true });
    await ins("io", { ioMode: "wait", ioName: "2", ioValue: "1" });
    await ins("io", { ioMode: "wait", ioName: "4", ioValue: "0", timeoutMs: 1500 });
    await ins("tool", { tool: tool2 });
    await e.run("program.addMoveJ", { program: prog, target: T2 });
    await e.run("program.addMoveJ", { program: prog, target: T8 });
    await e.run("program.addMoveL", { program: prog, target: T7 });

    const ours = buildIntermediate(e.ws, prog, { settings: generationSettings(e.services.settings), date: new Date(2026, 10, 4, 12, 50, 1) });
    const robodk = readFileSync(path.join(EVIDENCE, "ABB_RAPID_IRC5/intermediate_PostPgProg.py"), "utf8");
    expect(calls(ours.text)).toEqual(calls(robodk));
    expect(ours.total).toBe(12);
    expect(ours.text).toContain("print('Total instructions: 12')");
    expect(ours.text).toContain('r.RunMessage(r"""Program generated by Enginuity v1.0.0 for ABB IRB 120-3/0.6 on 04/11/2026 12:50:01""",True)');

     
    for (const [post, file] of [
      ["ABB_RAPID_IRC5", "PgProg.mod"],
      ["KUKA_KRC4", "PgProg.src"],
      ["Universal_Robots", "PgProg.script"],
      ["Fanuc_R30i", "PgProg.LS"],
    ] as const) {
      const out = spawnSync("python3", ["-I", path.join(ROOT, "python/robocraft_post/cli.py"), "--post", post], { input: JSON.stringify({ intermediate: ours.text }), encoding: "utf8" });
      const reply = JSON.parse(out.stdout) as { ok: boolean; files: { name: string; content: string }[]; error?: string };
      expect(reply.ok, reply.error ?? "").toBe(true);
      const generated = reply.files.find((f) => f.name === file)!.content;
      const reference = readFileSync(path.join(EVIDENCE, post, file), "utf8");
       
       
      const mask = (s: string) =>
        s
          .replace(/RoboDK(?= sequence)/g, "Enginuity")
          .replace(/Program generated by (?:Robo\w+|Enginuity) v[\d.]+ for /g, "Program generated by X for ")
          .replace(/on [\dX]{2}\/[\dX]{2}\/[\dX]{4} \d\d:\d\d:\d\d/g, "on DATE")
          .replace(/^ {3}[12]: {2}! .* ;$/gm, "HEADER");
      expect(mask(generated)).toBe(mask(reference));
    }
  });

  it("R-POSTGEN-27: ProgMoveJType=1 writes every MoveJ as joints only", async () => {
    const { e, robot } = await abbStation();
    const frame = await frameAt(e, robot.id, "Frame S", [1234.57, -98.7654, 50.5, 30, 0, 0]);
    const T1 = await target(e, robot.id, frame, "T1", [-640.584, 506.98, 371.534, 150, 50, 180], [0, -10, 20, 0, 30, 1.31556e-14]);
    const prog = id(await e.run("program.add", { name: "SetProg", robot: robot.id }));
    await e.run("program.addMoveJ", { program: prog, target: T1 });
    const s = { ...generationSettings(e.services.settings), moveJType: 1 };
    expect(calls(buildIntermediate(e.ws, prog, { settings: s }).text)).toContain("r.MoveJ(None,[0,-10,20,0,30,1.31556e-14],None)");
    const names = { ...generationSettings(e.services.settings), moveNames: true };
    expect(buildIntermediate(e.ws, prog, { settings: names }).text).toContain('r._TargetName=r"""T1"""\r\nr.MoveJ(p(-640.584,506.98,371.534,150,50,180)');
  });

  async function mainCall() {
    const { e, robot } = await abbStation();
    const frame = await frameAt(e, robot.id, "Frame S", [1234.57, -98.7654, 50.5, 30, 0, 0]);
    const T1 = await target(e, robot.id, frame, "T1", [-640.584, 506.98, 371.534, 150, 50, 180], [0, -10, 20, 0, 30, 1.31556e-14]);
    const T3 = await target(e, robot.id, frame, "T3 joint", null, [20, -10, 20, 0, 30, 0]);
    const main = id(await e.run("program.add", { name: "MainCall", robot: robot.id }));
    const sub = id(await e.run("program.add", { name: "SubProg2", robot: robot.id }));
    await e.run("program.addInstruction", { program: main, kind: "frame", frame });
    await e.run("program.addMoveJ", { program: main, target: T1 });
    await e.run("program.addInstruction", { program: main, kind: "call", text: "SubProg2" });
    await e.run("program.addInstruction", { program: main, kind: "call", text: "NotAProgram" });
    await e.run("program.addInstruction", { program: sub, kind: "frame", frame });
    await e.run("program.addMoveJ", { program: sub, target: T3 });
    return { e, main };
  }

  it("R-POSTGEN-30: program calls are generated as subprograms after the main program", async () => {
    const { e, main } = await mainCall();
    const ours = buildIntermediate(e.ws, main, { settings: generationSettings(e.services.settings) });
    const robodk = readFileSync(path.join(EVIDENCE, "settings/v11_subprogram_call/intermediate_PostMainCall.py"), "utf8");
    expect(calls(ours.text)).toEqual(calls(robodk));
    expect(ours.total).toBe(4);
  });

  it("R-POSTGEN-30: ProgInlineSubprogs=1 inlines the called program", async () => {
    const { e, main } = await mainCall();
    const s = { ...generationSettings(e.services.settings), inline: true };
    const ours = buildIntermediate(e.ws, main, { settings: s });
    const robodk = readFileSync(path.join(EVIDENCE, "settings/v12_subprogram_inline/intermediate_PostMainCall.py"), "utf8");
    expect(calls(ours.text)).toEqual(calls(robodk));
    expect(ours.total).toBe(3);
  });

  it("R-POSTGEN-22: ProgMaxLines adds lines_x_prog to the RobotPost constructor", async () => {
    const { e, main } = await mainCall();
    const s = { ...generationSettings(e.services.settings), maxLines: 5 };
    expect(buildIntermediate(e.ws, main, { settings: s }).text).toMatch(/robot_ptr=\d+, lines_x_prog=5\)/);
  });
});

describe("POST-GENERATE: program.generate end to end (server bridge)", () => {
  it("R-POSTGEN-38/48: files are written to the programs folder; the .urp is binary", async () => {
    process.env.ROBOCRAFT_DATA_DIR = mkdtempSync(path.join(tmpdir(), "rc-gen-"));
    const { generateProgram } = await import("@/server/post");
    const { e, robot } = await abbStation();
    e.services.post = generateProgram;
    const prog = id(await e.run("program.add", { name: "Bare Prog-1 (x)", robot: robot.id }));
    await e.run("program.addMoveJ", { program: prog, joints: [0, -10, 20, 0, 30, 0] });
    const res = (await e.run("program.generate", { program: prog, post: "Universal_Robots" })) as unknown as {
      program: string;
      total: number;
      files: { name: string; binary: boolean; path: string; content: string }[];
    };
    expect(res.program).toBe("BareProg1x");
    expect(res.total).toBe(1);
    expect(res.files.map((f) => f.name)).toEqual(["BareProg1x.script", "BareProg1x.urp"]);
    expect(res.files[1].binary).toBe(true);
    for (const f of res.files) expect(existsSync(f.path)).toBe(true);
    expect(res.files[0].content).toContain("movej([0.000000, -0.174533, 0.349066, 0.000000, 0.523599, 0.000000],accel_radss,speed_rads,t=0,r=0)");

    const missing = await e.tryRun("program.generate", { program: prog, post: "Fanuc_R30iA" });
    expect(missing.ok).toBe(false);
    expect(missing.error).toContain("Select a Post Processor for the robot ABB IRB 120-3/0.6");
  });
});
