def build(post, robot, nq, probe, axes_types=None, pulses=None):
    prog, total, body, extra = probe(post, robot, nq)
    return prog, header(post, prog, total, robot, nq, extra, axes_types, pulses) + body





def run_case(post, robot, nq, probe, label, axes_types=None, pulses=None):
    out_dir = os.path.join(EVIDENCE, post, label, probe.__name__[len("probe_"):])
    prog, lines = build(post, robot, nq, probe, axes_types, pulses)
    meta = {"post": post, "robot": robot, "nq": nq, "axes": axes_types or AXES[nq]}
    if pulses:
        meta["pulses_x_deg"] = pulses
    return execute(out_dir, prog, lines, meta)


def execute(out_dir, prog, lines, meta):
    pass
    if os.path.isdir(out_dir):
        shutil.rmtree(out_dir)
    os.makedirs(out_dir)
    lines = lines + ["r.ProgSave(%s,%s,False,False)" % (s(out_dir + "/"), s(prog))]
    text = "\n".join(lines) + "\n"
    with tempfile.TemporaryDirectory(prefix="pgbb-") as work:
        script = os.path.join(work, "Post%s.py" % prog)
        with open(script, "w", encoding="utf-8") as fh:
            fh.write(text)
        env = {
            "PATH": "/usr/bin:/bin",
            "HOME": work,
            "TMPDIR": work + "/",
            "PYTHONPATH": PYPATH,
            "PYTHONIOENCODING": "utf8",
            "PYTHON_EXEC": PYTHON,
            "ROBODK_API_PORT": "1",
        }
        if os.environ.get("POSTGEN_HOOKS"):
            
            env["PYTHONPATH"] = HOOKS + ":" + PYPATH
            env["POSTGEN_HOOK_DIR"] = out_dir
            meta = dict(meta, hooks=True)
        try:
            res = subprocess.run(["sandbox-exec", "-p", SANDBOX, PYTHON, script], cwd=work, env=env, capture_output=True, timeout=60)
            code, out, err = res.returncode, res.stdout, res.stderr
        except subprocess.TimeoutExpired as exc:
            code, out, err = "timeout", exc.stdout or b"", exc.stderr or b""
        stray = sorted(f for f in os.listdir(work) if f != os.path.basename(script))
    with open(os.path.join(out_dir, "intermediate_Post%s.py" % prog), "w", encoding="utf-8") as fh:
        fh.write(text)
    with open(os.path.join(out_dir, "_run.json"), "w", encoding="utf-8") as fh:
        json.dump(dict(meta, exit=code, stray_files=stray), fh, indent=1)
    with open(os.path.join(out_dir, "_stdout.txt"), "wb") as fh:
        fh.write(out or b"")
    with open(os.path.join(out_dir, "_stderr.txt"), "wb") as fh:
        fh.write(err or b"")
    files = sorted(f for f in os.listdir(out_dir) if not f.startswith(("_", "intermediate_")))
    return code, files, (err or b"").decode("utf-8", "replace").strip().splitlines()[-1:] if err else []


