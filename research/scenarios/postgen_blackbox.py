def _robot_files():
    out = {}
    for base, _dirs, files in os.walk(LIBRARY):
        for f in files:
            if f.endswith(".robot"):
                out.setdefault(f, os.path.join(base, f))
    return out


def robot_facts(file):
    pass
    import struct
    import zlib

    path = _robot_files().get(file)
    if not path:
        return None, None
    with open(path, "rb") as fh:
        raw = zlib.decompress(fh.read()[4:])
    n_vals = int(struct.unpack_from("<4d", raw, 0)[1])
    h = struct.unpack_from("<%dd" % n_vals, raw, 0)
    rows = int(h[2])
    cell = lambda c, r: h[c * rows + r]  # noqa: E731
    nq = int(round(cell(1, 1)))
    kinds = "".join("L" if round(cell(10 + j, 4)) == 1 else "R" for j in range(nq))
    return kinds, h


def pulses_text(robot_name, h, nq):
    if h is None:
        return None
    rows = int(h[2])
    legacy = h[3 * rows + 2]
    n = robot_name.lower()
    if not (abs(legacy - 3.4) < 0.5 or "motoman" in n or "yaskawa" in n or n.startswith(("gsk", "epson", "cloos"))):
        return None
    vals = [h[49 * rows + j] for j in range(nq)]
    return "[%s]" % ",".join(("-" if v < 0 and not ("%.6f" % v).startswith("-") else "") + "%.6f" % v for v in vals)


def jl(values):
    pass
    return "[" + ",".join(_g(v) for v in values) + "]"


def _g(v):
    s = "%.6g" % v
